"""
Google Antigravity: Reasoning Protocols
========================================

The Holmesian method is NOT pure deduction, but a complex hybrid.
Understanding the distinction is critical to grasping how Holmes 
solves cases that baffle Scotland Yard.

DEDUCTION: General → Specific (guaranteed if premises true)
  "All men are mortal; Socrates is a man; therefore, Socrates is mortal"

INDUCTION: Specific → General (probabilistic)
  "Every swan I've seen is white; therefore, all swans are white"

ABDUCTION: Observation → Best Explanation (plausible)
  THE PRIMARY ENGINE - generating the narrative that fits the facts

"In solving a problem of this sort, the grand thing is to be able 
to reason backwards. That is a very useful accomplishment and a 
very easy one, but people do not practice it much."
- Sherlock Holmes, A Study in Scarlet
"""

from dataclasses import dataclass, field
from typing import List, Dict, Optional, Any, Tuple, Set
from enum import Enum
from datetime import datetime
import re


# ==============================================================================
# Core Data Structures
# ==============================================================================

class ReasoningType(Enum):
    """Types of logical reasoning."""
    DEDUCTION = "deduction"
    INDUCTION = "induction"
    ABDUCTION = "abduction"
    BACKWARD = "backward"  # Reasoning from effect to cause


class CertaintyLevel(Enum):
    """Level of certainty in conclusions."""
    ABSOLUTE = "absolute"        # Deductive certainty (contingent on premises)
    PROBABILISTIC = "probabilistic"  # Inductive probability
    PLAUSIBLE = "plausible"      # Abductive best guess
    SPECULATIVE = "speculative"  # Low confidence


@dataclass
class Premise:
    """A premise in a logical argument."""
    statement: str
    is_universal: bool      # "All X are Y" vs "This X is Y"
    confidence: float       # How confident we are in this premise
    source: str            # Where this premise comes from
    evidence: List[str] = field(default_factory=list)


@dataclass
class Observation:
    """An observation that needs explanation."""
    id: str
    description: str
    context: str
    code_snippet: Optional[str] = None
    location: Optional[str] = None
    anomaly_score: float = 0.5  # How unusual is this observation


@dataclass
class Conclusion:
    """A conclusion drawn from reasoning."""
    statement: str
    reasoning_type: ReasoningType
    certainty: CertaintyLevel
    confidence: float
    premises_used: List[Premise]
    reasoning_chain: List[str]


@dataclass
class Hypothesis:
    """A hypothesis generated by abductive reasoning."""
    id: str
    explanation: str
    explains_observations: List[str]  # IDs of observations this explains
    assumptions: List[str]
    complexity_score: float  # Lower is better (Occam's Razor)
    plausibility: float
    competing_explanations: List[str] = field(default_factory=list)


@dataclass
class CausalChain:
    """A chain of cause and effect for backward reasoning."""
    effect: str
    potential_causes: List[Tuple[str, float]]  # (cause, probability)
    selected_cause: Optional[str] = None
    reasoning: str = ""


