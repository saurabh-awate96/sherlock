    # --------------------------------------------------------------------------
    # Deductive Reasoning
    # --------------------------------------------------------------------------
    
    def deduce(
        self,
        premises: List[Premise],
        target_conclusion: Optional[str] = None
    ) -> Optional[Conclusion]:
        """
        Top-down deductive reasoning from general to specific.
        
        If the premises are true, the conclusion MUST be true.
        This gives us ABSOLUTE certainty (contingent on premises).
        
        Example:
          Premise 1: All external calls before state updates enable reentrancy
          Premise 2: This withdraw() makes an external call before state update
          Conclusion: This withdraw() enables reentrancy
        
        Args:
            premises: List of premises (universal and specific)
            target_conclusion: Optional specific conclusion to validate
        
        Returns:
            Conclusion if one can be derived, None otherwise
        """
        # Separate universal and specific premises
        universal = [p for p in premises if p.is_universal]
        specific = [p for p in premises if not p.is_universal]
        
        if not universal or not specific:
            return None
        
        # Try to form a syllogism
        for univ in universal:
            for spec in specific:
                conclusion = self._apply_syllogism(univ, spec)
                if conclusion:
                    if target_conclusion is None or target_conclusion in conclusion.statement:
                        return conclusion
        
        return None
    
    def _apply_syllogism(self, universal: Premise, specific: Premise) -> Optional[Conclusion]:
        """
        Apply syllogistic reasoning.
        
        Pattern: "All X are Y" + "This Z is X" → "This Z is Y"
        """
        # Simple pattern matching for syllogism
        # In production, this would use more sophisticated logic
        
        # Extract patterns
        all_pattern = r"(?:All|Any|Every)\s+(\w+(?:\s+\w+)*)\s+(?:are|is|can|enable|have)\s+(.+)"
        if_pattern = r"If\s+(.+?),?\s+(?:it|they)\s+(?:may be|is|are|can be)\s+(.+)"
        
        universal_match = re.match(all_pattern, universal.statement, re.IGNORECASE)
        if_match = re.match(if_pattern, universal.statement, re.IGNORECASE)
        
        if universal_match:
            subject_category = universal_match.group(1).lower()
            predicate = universal_match.group(2)
            
            # Check if specific premise matches the subject category
            if subject_category in specific.statement.lower():
                # Form conclusion
                conclusion_statement = f"{specific.statement} → {predicate}"
                
                # Calculate confidence (product of premise confidences)
                confidence = universal.confidence * specific.confidence
                
                return Conclusion(
                    statement=conclusion_statement,
                    reasoning_type=ReasoningType.DEDUCTION,
                    certainty=CertaintyLevel.ABSOLUTE,
                    confidence=confidence,
                    premises_used=[universal, specific],
                    reasoning_chain=[
                        f"Universal: {universal.statement}",
                        f"Specific: {specific.statement}",
                        f"Therefore: {conclusion_statement}"
                    ]
                )
        
        if if_match:
            condition = if_match.group(1).lower()
            result = if_match.group(2)
            
            # Check if specific premise matches the condition
            if any(word in specific.statement.lower() for word in condition.split()):
                conclusion_statement = f"This code {result}"
                confidence = universal.confidence * specific.confidence
                
                return Conclusion(
                    statement=conclusion_statement,
                    reasoning_type=ReasoningType.DEDUCTION,
                    certainty=CertaintyLevel.ABSOLUTE,
                    confidence=confidence,
                    premises_used=[universal, specific],
                    reasoning_chain=[
                        f"Rule: {universal.statement}",
                        f"Observed: {specific.statement}",
                        f"Deduced: {conclusion_statement}"
                    ]
                )
        
        return None
    
    def deduce_from_elimination(
        self,
        possibilities: List[str],
        eliminated: Set[str],
        reasoning: List[str]
    ) -> Conclusion:
        """
        "When you have eliminated the impossible, whatever remains, 
        however improbable, must be the truth."
        
        Args:
            possibilities: All possible explanations
            eliminated: Set of eliminated possibilities
            reasoning: Why each was eliminated
        
        Returns:
            Conclusion with remaining possibility
        """
        remaining = [p for p in possibilities if p not in eliminated]
        
        if len(remaining) == 1:
            return Conclusion(
                statement=remaining[0],
                reasoning_type=ReasoningType.DEDUCTION,
                certainty=CertaintyLevel.ABSOLUTE,
                confidence=0.95,  # High confidence via elimination
                premises_used=[
                    Premise(
                        statement=f"Eliminated: {e}",
                        is_universal=False,
                        confidence=0.9,
                        source="elimination"
                    )
                    for e in eliminated
                ],
                reasoning_chain=reasoning + [f"Remaining: {remaining[0]}"]
            )
        elif len(remaining) == 0:
            # All eliminated - need new possibilities
            return Conclusion(
                statement="No valid explanation found - requires new hypotheses",
                reasoning_type=ReasoningType.DEDUCTION,
                certainty=CertaintyLevel.SPECULATIVE,
                confidence=0.1,
                premises_used=[],
                reasoning_chain=reasoning + ["All possibilities eliminated"]
            )
        else:
            # Multiple remaining - need more evidence
            return Conclusion(
                statement=f"Multiple possibilities remain: {remaining}",
                reasoning_type=ReasoningType.DEDUCTION,
                certainty=CertaintyLevel.PROBABILISTIC,
                confidence=1.0 / len(remaining),
                premises_used=[],
                reasoning_chain=reasoning + [f"Remaining: {remaining}"]
            )
    
    # --------------------------------------------------------------------------
    # Inductive Reasoning
    # --------------------------------------------------------------------------
    
    def induce(
        self,
        observations: List[Observation],
        min_observations: int = 3
    ) -> Optional[Conclusion]:
        """
        Bottom-up reasoning from specific observations to general patterns.
        
        Used for building profiles from accumulated details.
        Example: Seeing scratches on phone + shaking hands + smell of alcohol
                 → User is an alcoholic
        
        This gives PROBABILISTIC certainty - the more observations,
        the more confident the generalization.
        
        Args:
            observations: List of specific observations
            min_observations: Minimum observations needed to generalize
        
        Returns:
            General pattern conclusion
        """
        if len(observations) < min_observations:
            return None
        
        # Find common themes in observations
        themes = self._extract_themes(observations)
        
        if not themes:
            return None
        
        # Form generalization from most common theme
        primary_theme = max(themes.items(), key=lambda x: x[1])
        theme_name, theme_count = primary_theme
        
        # Confidence scales with observation count
        confidence = min(0.95, 0.5 + (theme_count / len(observations)) * 0.4)
        
        return Conclusion(
            statement=f"Pattern detected: {theme_name} (observed {theme_count}/{len(observations)} times)",
            reasoning_type=ReasoningType.INDUCTION,
            certainty=CertaintyLevel.PROBABILISTIC,
            confidence=confidence,
            premises_used=[
                Premise(
                    statement=obs.description,
                    is_universal=False,
                    confidence=1 - obs.anomaly_score,
                    source="observation"
                )
                for obs in observations
            ],
            reasoning_chain=[
                f"Observed: {obs.description}" for obs in observations
            ] + [f"Generalized to: {theme_name}"]
        )
    
    def _extract_themes(self, observations: List[Observation]) -> Dict[str, int]:
        """Extract common themes from observations."""
        themes = {}
        
        # Security-specific theme detection
        theme_keywords = {
            "reentrancy": ["external call", "callback", "state after", "re-enter"],
            "oracle_risk": ["price", "oracle", "spot", "reserve", "getPrice"],
            "access_control": ["owner", "admin", "permission", "auth", "require"],
            "arithmetic": ["overflow", "underflow", "multiply", "divide"],
            "flash_loan": ["flash", "loan", "atomic", "same block"],
            "unchecked_return": ["return value", "unchecked", "ignored"],
        }
        
        for obs in observations:
            desc_lower = obs.description.lower()
            for theme, keywords in theme_keywords.items():
                if any(kw in desc_lower for kw in keywords):
                    themes[theme] = themes.get(theme, 0) + 1
        
        return themes
    
    # --------------------------------------------------------------------------
    # Abductive Reasoning (THE PRIMARY ENGINE)
    # --------------------------------------------------------------------------
    
    def abduce(
        self,
        observation: Observation,
        max_hypotheses: int = 3
    ) -> List[Hypothesis]:
        """
        Inference to the Best Explanation.
        
        THE PRIMARY ENGINE of Holmesian reasoning. Takes an observation
        (a result) and infers the most likely CAUSE that would explain it.
        
        Unlike deduction (which guarantees truth), abduction guarantees 
        only PLAUSIBILITY based on available data. It is the creative 
        leap—the formulation of a hypothesis that fits the facts better 
        than any competing hypothesis.
        
        Example:
          Observation: The victim's coat is wet but jewelry is dry
          Hypothesis A: She was caught in rain with an umbrella
          Hypothesis B: She was in a cab (coat got wet entering/exiting)
          → Select hypothesis that explains most with fewest assumptions
        
        Args:
            observation: The observation to explain
            max_hypotheses: Maximum hypotheses to generate
        
        Returns:
            List of plausible hypotheses, ranked by plausibility
        """
        self.observations[observation.id] = observation
        
        hypotheses = []
        
        # Generate hypotheses based on observation content
        hypothesis_generators = [
            self._generate_reentrancy_hypothesis,
            self._generate_oracle_hypothesis,
            self._generate_access_control_hypothesis,
            self._generate_flash_loan_hypothesis,
            self._generate_general_hypothesis,
        ]
        
        for generator in hypothesis_generators:
            hyp = generator(observation)
            if hyp and hyp.plausibility > 0.1:
                hypotheses.append(hyp)
        
        # Apply Occam's Razor - prefer simpler explanations
        for hyp in hypotheses:
            complexity_penalty = len(hyp.assumptions) * self.occam_weight
            hyp.plausibility *= (1 - complexity_penalty)
        
        # Sort by plausibility
        hypotheses.sort(key=lambda h: h.plausibility, reverse=True)
        
        # Store and return top hypotheses
        for hyp in hypotheses[:max_hypotheses]:
            self.hypotheses[hyp.id] = hyp
        
        print(f"[Abduction] Generated {len(hypotheses)} hypotheses for observation")
        
        return hypotheses[:max_hypotheses]
    
